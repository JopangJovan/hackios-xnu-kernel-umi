#!/usr/bin/env python3
"""Generate an ignored C include holding this UMI's own sensor registry.

The SLPI sensors registry asks APSS (over the FastRPC apps_std reverse
listener) for the directory named by sns_reg_config's "file=output=" line,
/mnt/vendor/persist/sensors/registry/registry, and reads every file it lists.
Android's sscrpcd serves the real persist partition; HakiOS serves the copy
the user pulled from this very phone (fw-sensors/registry.tar, whose members
are registry/registry/<name> and registry/sns_reg_version).  Nothing here
changes a byte of that content: the generated table is read-only, in the
archive's own member order (which is the order the files were listed in).
"""
import argparse
import tarfile
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument('--registry', type=Path, required=True)
parser.add_argument('--output', type=Path, required=True)
args = parser.parse_args()

PREFIX = 'registry/registry/'
VERSION = 'registry/sns_reg_version'
MAX_NAME = 254          # apps_std_DIRENT.name is char[255], NUL included


def literal(data: bytes) -> str:
    """A C string literal (split into pieces) holding exactly these bytes."""
    pieces, piece = [], ''
    for b in data:
        c = chr(b)
        if c == '\\':
            piece += '\\\\'
        elif c == '"':
            piece += '\\"'
        elif 0x20 <= b < 0x7f and c != '?':
            piece += c
        else:
            piece += f'\\{b:03o}'      # three octal digits: never absorbs the next char
        if len(piece) >= 160:
            pieces.append(piece)
            piece = ''
    pieces.append(piece)
    return '\n\t    '.join(f'"{p}"' for p in pieces)


files, version = [], b''
if args.registry.is_file():
    with tarfile.open(args.registry) as tar:
        for member in tar.getmembers():
            if not member.isfile():
                continue
            if member.name == VERSION:
                version = tar.extractfile(member).read()
            elif member.name.startswith(PREFIX):
                name = member.name[len(PREFIX):]
                if not name or '/' in name or len(name.encode()) > MAX_NAME:
                    raise SystemExit(f'{args.registry}: unusable registry member {member.name!r}')
                files.append((name, tar.extractfile(member).read()))

lines = [
    '/* Generated by devices/xiaomi-mi-10/tools/embed-sensor-registry.py from',
    ' * fw-sensors/registry.tar (this device\'s own persist registry); do not edit. */',
    f'#define SLPI_REGISTRY_FILE_COUNT {len(files)}u',
    f'#define SLPI_REGISTRY_VERSION_LENGTH {len(version)}u',
    f'static const char slpi_registry_version[] = {literal(version)};',
    'static const struct slpi_fastrpc_registry_file slpi_registry_files[] = {',
]
for name, data in files:
    lines.append(f'\t{{ "{name}", {len(data)}u,\n\t    {literal(data)} }},')
if not files:
    lines.append('\t{ "", 0u, "" },     /* no registry.tar: an empty directory */')
lines.append('};')
contents = '\n'.join(lines) + '\n'
args.output.parent.mkdir(parents=True, exist_ok=True)
if not args.output.exists() or args.output.read_text() != contents:
    args.output.write_text(contents)
print(f'embedded local sensor registry: {len(files)} files, '
      f'{sum(len(d) for _, d in files)} bytes, sns_reg_version {len(version)} bytes')
